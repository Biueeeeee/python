def info_table(
    rows,
    styles,
    label_width=45 * mm,
    value_width=125 * mm,
    bg="#F4F7F6",
    border="#C5D6D4"
):

    data = []

    # 將資料轉成兩欄格式
    for label, value in rows:

        data.append([
            Paragraph(
                escape_text(label),
                styles["label"]
            ),

            Paragraph(
                escape_text(value),
                styles["small"]
            ),
        ])

    # 建立表格
    table = Table(
        data,
        colWidths=[label_width, value_width]
    )

    # 設定表格樣式
    table.setStyle(TableStyle([

        # 背景色
        ("BACKGROUND",
         (0, 0), (-1, -1),
         colors.HexColor(bg)),

        # 外框
        ("BOX",
         (0, 0), (-1, -1),
         0.5,
         colors.HexColor(border)),

        # 內框線
        ("INNERGRID",
         (0, 0), (-1, -1),
         0.3,
         colors.HexColor("#DDE7E5")),

        # padding
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),

        # 內容靠上
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))

    return table


# ============================================================
# 條列清單
# ============================================================

def bullet_list(items, styles):

    story = []

    # 若沒有資料則顯示 None
    if not items:
        items = ["None"]

    # 建立每一項 bullet
    for item in items:

        story.append(
            Paragraph(
                f"- {escape_text(item)}",
                styles["bullet"]
            )
        )

    return story


