# 取得所有原始職缺資料
# ============================================================

# 功能：
# 1. 抓取 104
# 2. 抓取 1111
# 3. 如果太少則 fallback
# 4. 去除重複職缺
# 5. 依相關度排序
# 6. 回傳最終職缺列表
#
# 這是整個「職缺蒐集系統」的核心函式。
def get_raw_jobs(job_title, location, salary_min):

    # 顯示目前正在抓取 104
    print("Fetching 104 jobs...")

    # 呼叫 104 抓取函式
    jobs_104 = fetch_104_jobs_direct(
        job_title=job_title,
        location=location,
        salary_min=salary_min,

        # 每平台最大抓取數
        limit=FETCH_PER_PLATFORM,
    )

    # 如果抓到的職缺太少
    #
    # 代表：
    # 1. 104 改版
    # 2. 被限制
    # 3. 搜尋條件太少
    #
    # 就啟用 fallback
    if len(jobs_104) < 10:
        print("104 direct results are too few. Using fallback search...")

        # extend()
        # 將 fallback 結果加入 jobs_104
        jobs_104.extend(
            fallback_search_platform(
                platform="104 Job Bank",
                domain="104.com.tw",
                job_title=job_title,
                location=location,
                salary_min=salary_min,
                limit=FETCH_PER_PLATFORM,
            )
        )


    # ========================================================
    # 抓取 1111
    # ========================================================

    print("Fetching 1111 jobs...")
    jobs_1111 = fetch_1111_jobs_direct(
        job_title=job_title,
        location=location,
        salary_min=salary_min,
        limit=FETCH_PER_PLATFORM,
    )

    # 如果 1111 結果太少
    if len(jobs_1111) < 10:
        print("1111 direct results are too few. Using fallback search...")

        # 加入 fallback 搜尋結果
        jobs_1111.extend(
            fallback_search_platform(
                platform="1111 Job Bank",
                domain="1111.com.tw",
                job_title=job_title,
                location=location,
                salary_min=salary_min,
                limit=FETCH_PER_PLATFORM,
            )
        )


    # ========================================================
    # 去除重複職缺
    # ========================================================

    # 儲存不重複職缺
    unique = []

    # 用來記錄已出現職缺
    #
    # set 查詢速度非常快
    seen = set()

    # 合併 104 + 1111
    for job in jobs_104 + jobs_1111:
        url = job.get("url", "")

        # 建立唯一 key
        #
        # 優先使用 URL
        #
        # 因為同一職缺 URL 通常固定
        #
        # 如果沒有 URL：
        # 使用：
        # platform|title|company
        #
        # 當作替代唯一值
        key = url if url else f"{job.get('platform')}|{job.get('title')}|{job.get('company')}"

        if key in seen:
            continue

        # 加入 seen
        seen.add(key)

        # 加入 unique
        unique.append(job)


    # ========================================================
    # 排序職缺
    # ========================================================

    # 根據 keyword_score 排序
    #
    # reverse=True
    # 代表由大到小
    #
    # 分數高：
    # 表示比較符合搜尋需求
    unique.sort(key=lambda x: x.get("keyword_score", 0), reverse=True)


    # ========================================================
    # 回傳前 N 筆
    # ========================================================
    return unique[:TOTAL_JOBS_TO_FETCH]