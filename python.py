# 技能 chip 樣式表格
# ============================================================

def chip_table(items, styles, max_cols=3):

    # 清理空值
    clean_items = [
        safe_text(x)
        for x in items
        if safe_text(x)
    ]

    # 若沒有資料
    if not clean_items:
        clean_items = ["None"]

    rows = []
    row = []

    # 每 max_cols 個換一列
    for item in clean_items:

        row.append(
            Paragraph(
                escape_text(item),
                styles["small"]
            )
        )

        # 換行
        if len(row) == max_cols:
            rows.append(row)
            row = []

    # 最後不足 max_cols 補空白
    if row:

        while len(row) < max_cols:
            row.append("")

        rows.append(row)

    # 建立表格
    table = Table(
        rows,
        colWidths=[52 * mm] * max_cols
    )

    # 設定 chip 樣式
    table.setStyle(TableStyle([

        ("BACKGROUND",
         (0, 0), (-1, -1),
         colors.HexColor("#E8F0E6")),

        ("BOX",
         (0, 0), (-1, -1),
         0.3,
         colors.HexColor("#B7C9A7")),

        ("INNERGRID",
         (0, 0), (-1, -1),
         0.3,
         colors.white),

        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),

        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))

    return table


