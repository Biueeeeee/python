# 從文字中猜測公司名稱
# ============================================================

# 功能：
# 從一大段文字中，用 regex 抓出可能的公司名稱
#
# 例如：
# text =
# "台積電股份有限公司誠徵 Python 工程師"
#
# 會抓出：
# "台積電股份有限公司"
def guess_company_from_text(text):

    # re.search()：
    # 在文字中搜尋第一個符合 regex 的內容
    #
    # regex 解釋：
    #
    # [\u4e00-\u9fa5A-Za-z0-9（）()股份有限公司]
    #
    # 允許的字元：
    # 1. 中文
    # 2. 英文大小寫
    # 3. 數字
    # 4. 中文括號（）
    # 5. 英文括號()
    # 6. 「股份有限公司」中的字
    #
    # {2,40}
    # 長度限制 2~40 個字
    #
    # (?:股份有限公司|有限公司|公司)
    #
    # 公司名稱必須以：
    # 1. 股份有限公司
    # 2. 有限公司
    # 3. 公司
    #
    # 作為結尾
    m = re.search(
        r"([\u4e00-\u9fa5A-Za-z0-9（）()股份有限公司]{2,40}(?:股份有限公司|有限公司|公司))",
        text,
    )

    # 如果有找到符合內容
    if m:

        # m.group(1)
        # 代表第一組括號匹配到的內容
       return m.group(1)

    # 如果沒有找到回傳
    return "Not clearly shown"


